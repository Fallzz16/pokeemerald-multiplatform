import unittest

from tools.grandworld_native.native_asm import normalize_host_assembly


class NativeAsmTests(unittest.TestCase):
    def test_arm_comments_on_data_directives_are_host_compatible(self):
        original = '\t.byte 12, 34 @ World generated palette\n\t.long 0 @\n'
        result, count = normalize_host_assembly(original)
        self.assertEqual(result, '\t.byte 12, 34 # World generated palette\n\t.long 0 #\n')
        self.assertEqual(count, 2)

    def test_real_menu_compound_string_section_preserves_data(self):
        original = (
            '.section\t.rodata.compound_string.08e3c907b5827d0c,"aM",%progbits,2 @,"a"\n'
            '.type sCompoundString_08e3c907b5827d0c, @object\n'
            '.size sCompoundString_08e3c907b5827d0c, 2\n'
            'sCompoundString_08e3c907b5827d0c:\n'
            '.ascii "|\\377"\n'
        )
        converted, count = normalize_host_assembly(original)
        self.assertEqual(count, 1)
        self.assertIn(
            '.section\t.rodata.compound_string.08e3c907b5827d0c,"aM",%progbits,2\n',
            converted)
        self.assertIn('.type sCompoundString_08e3c907b5827d0c, @object\n', converted)
        self.assertIn('.ascii "|\\377"\n', converted)
        self.assertEqual(converted.count('sCompoundString_08e3c907b5827d0c:'), 1)

    def test_full_line_arm_comments(self):
        original = "\t@ generated by World charmap\n    @ copied assets\n"
        converted, count = normalize_host_assembly(original)
        self.assertEqual(count, 2)
        self.assertEqual(converted, "\t# generated by World charmap\n    # copied assets\n")

    def test_quoted_asset_and_elf_type_are_not_changed(self):
        original = (
            '.section .rodata,"a",@progbits\n'
            '.incbin "graphics/@character/sample.bin"\n'
            '.type filename, @object\n'
            '\tcall symbol@PLT\n'
            '\t# original host comment\n'
        )
        self.assertEqual(normalize_host_assembly(original), (original, 0))

    def test_do_not_mutate_byte_literals_or_symbols(self):
        original = (
            '\t.byte 0x40, 0x41\n'
            '\t.ascii "mail@me"\n'
            '\t.ascii "constant @ fake comment"\n'
            '\t.byte 0xFF # host comment\n'
        )
        self.assertEqual(normalize_host_assembly(original), (original, 0))

    def test_idempotent(self):
        source = '.long 5 @ generated\n @ note\n'
        first, changed = normalize_host_assembly(source)
        second, again = normalize_host_assembly(first)
        self.assertEqual(changed, 2)
        self.assertEqual(again, 0)
        self.assertEqual(first, second)


if __name__ == '__main__':
    unittest.main()
